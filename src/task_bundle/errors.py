def exit_code_for_error(code: ErrorCode) -> int:
    if code in _CONFIG_CODES:
        return 2
    if code in _VALIDATION_CODES:
        return 4
    if code in _SOLVER_CODES:
        return 5
    if code in _PATCH_CODES:
        return 6
    return 3
